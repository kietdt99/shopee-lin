$ErrorActionPreference = 'Stop'

$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$localWorkspace = Join-Path $projectRoot 'supabase\local'
$localSupabase = Join-Path $localWorkspace 'supabase'
$migrationDir = Join-Path $localSupabase 'migrations'
$configSource = Join-Path $projectRoot 'supabase\local-dev\config.toml'
$schemaSource = Join-Path $projectRoot 'supabase\schema.sql'
$financialRpcMigrationSource = Join-Path $projectRoot 'supabase\migrations\20261121_z_serialize_order_financial_rpcs.sql'
$softDeleteMigrationSource = Join-Path $projectRoot 'supabase\migrations\20261122100000_soft_delete_and_append_only_history.sql'
$installmentGuardsMigrationSource = Join-Path $projectRoot 'supabase\migrations\20261122130000_installment_payment_guards.sql'
$profileAvatarMigrationSource = Join-Path $projectRoot 'supabase\migrations\20261122120000_profile_avatars.sql'
$legacyImportSqlPath = Join-Path $projectRoot 'supabase\local\import_legacy_apply.sql'
$legacyImportMarker = Join-Path $localWorkspace '.legacy-import-v1.applied'
$generatedEnvPath = Join-Path $projectRoot '.env.development.local'
$generatedEnvMarker = '# Generated by scripts/dev/start-local-supabase.ps1. Local Supabase only.'
$localPassword = 'Shopee-Lin-Local-Only-2026'
$accounts = @(
  @{ label = 'Admin'; email = 'tuankiet141199@gmail.com' },
  @{ label = 'Tester Quèn'; email = 'tuankiet141199+lin-test@gmail.com' }
)

function Stop-WithMessage([string]$Message) {
  throw $Message
}

function Read-DotEnvValue([string]$Line) {
  $separator = $Line.IndexOf('=')
  if ($separator -lt 1) { return $null }
  $value = $Line.Substring($separator + 1).Trim()
  if ($value.StartsWith('"')) {
    try { return ($value | ConvertFrom-Json -ErrorAction Stop) } catch { return $null }
  }
  return $value
}

if (-not (Test-Path -LiteralPath $generatedEnvPath)) {
  # The Vite development-specific file overrides .env.local only for `pnpm dev`.
} else {
  $firstLine = Get-Content -LiteralPath $generatedEnvPath -TotalCount 1
  if ($firstLine -cne $generatedEnvMarker) {
    Stop-WithMessage '.env.development.local already exists and was not generated by this script; refusing to overwrite it.'
  }
}

New-Item -ItemType Directory -Force -Path $migrationDir | Out-Null
Copy-Item -LiteralPath $configSource -Destination (Join-Path $localSupabase 'config.toml') -Force
Copy-Item -LiteralPath $schemaSource -Destination (Join-Path $migrationDir '20261122000000_local_schema.sql') -Force
Copy-Item -LiteralPath $financialRpcMigrationSource -Destination (Join-Path $migrationDir '20261122000001_order_financial_rpcs.sql') -Force
Copy-Item -LiteralPath $softDeleteMigrationSource -Destination (Join-Path $migrationDir '20261122100000_soft_delete_and_append_only_history.sql') -Force
Copy-Item -LiteralPath $profileAvatarMigrationSource -Destination (Join-Path $migrationDir '20261122120000_profile_avatars.sql') -Force
Copy-Item -LiteralPath $installmentGuardsMigrationSource -Destination (Join-Path $migrationDir '20261122130000_installment_payment_guards.sql') -Force

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Stop-WithMessage 'Local Supabase files are prepared. Docker Desktop is required to start them; install and start Docker Desktop, then run pnpm supabase:local:start again.'
}

Write-Host 'Starting the isolated local Supabase stack...'
$null = & pnpm exec supabase start --workdir $localWorkspace --output-format json 2>$null
if ($LASTEXITCODE -ne 0) {
  Stop-WithMessage 'Supabase local startup failed. Check that Docker Desktop is running, then retry.'
}

Write-Host 'Applying pending local migrations without resetting the local database...'
& pnpm exec supabase migration up --workdir $localWorkspace
if ($LASTEXITCODE -ne 0) {
  Stop-WithMessage 'Could not apply pending local migrations. No database reset was run; inspect the migration error and local data before taking further action.'
}

if (Test-Path -LiteralPath $legacyImportSqlPath) {
  if (-not (Test-Path -LiteralPath $legacyImportMarker)) {
    Write-Host 'Applying the one-time legacy workbook import to local Supabase...'
    & pnpm exec supabase db query --file $legacyImportSqlPath --workdir $localWorkspace | Out-Null
    if ($LASTEXITCODE -ne 0) {
      Stop-WithMessage 'The local legacy import failed. No import marker was written; inspect the local SQL/data before retrying.'
    }
    Set-Content -LiteralPath $legacyImportMarker -Value 'legacy-import-v1' -Encoding ascii
  }
} else {
  Write-Host 'No local legacy import file was found; local Supabase will start with an empty ledger.'
  Write-Host 'To include historical data, generate supabase/local/import_legacy_apply.sql and rerun this command.'
}

$statusLines = & pnpm exec supabase status --workdir $localWorkspace --output env 2>$null
if ($LASTEXITCODE -ne 0) {
  Stop-WithMessage 'Could not read local Supabase connection settings. No environment file was written.'
}

$status = @{}
foreach ($line in $statusLines) {
  if ($line -match '^([A-Z0-9_]+)=') {
    $status[$Matches[1]] = Read-DotEnvValue $line
  }
}

$apiUrl = [string]$status['API_URL']
$publishableKey = [string]$status['PUBLISHABLE_KEY']
$serviceRoleKey = [string]$status['SERVICE_ROLE_KEY']
if ($apiUrl -ne 'http://127.0.0.1:54321' -or [string]::IsNullOrWhiteSpace($publishableKey) -or [string]::IsNullOrWhiteSpace($serviceRoleKey)) {
  Stop-WithMessage 'Local Supabase did not report the expected loopback API URL and keys; refusing to configure the app.'
}

$envLines = @(
  $generatedEnvMarker,
  'VITE_SUPABASE_URL="http://127.0.0.1:54321"',
  ('VITE_SUPABASE_PUBLISHABLE_KEY="{0}"' -f $publishableKey),
  ('VITE_LOCAL_ADMIN_EMAIL="{0}"' -f $accounts[0].email),
  ('VITE_LOCAL_VIEWER_EMAIL="{0}"' -f $accounts[1].email),
  'VITE_LOCAL_LOGIN_SHORTCUTS="true"',
  ('VITE_LOCAL_DEV_PASSWORD="{0}"' -f $localPassword)
)
Set-Content -LiteralPath $generatedEnvPath -Value $envLines -Encoding ascii

$headers = @{
  apikey = $serviceRoleKey
  Authorization = "Bearer $serviceRoleKey"
}
$authUrl = $apiUrl + '/auth/v1/admin/users'
try {
  $userList = Invoke-RestMethod -Method Get -Uri ($authUrl + '?page=1&per_page=1000') -Headers $headers -TimeoutSec 20
  foreach ($account in $accounts) {
    $existing = @($userList.users | Where-Object { $_.email -ceq $account.email } | Select-Object -First 1)
    $body = @{
      email = $account.email
      password = $localPassword
      email_confirm = $true
      user_metadata = @{ full_name = $account.label }
    } | ConvertTo-Json -Depth 5 -Compress

    if ($existing.Count -gt 0) {
      $null = Invoke-RestMethod -Method Put -Uri ("{0}/{1}" -f $authUrl, $existing[0].id) -Headers $headers -ContentType 'application/json' -Body $body -TimeoutSec 20
    } else {
      $null = Invoke-RestMethod -Method Post -Uri $authUrl -Headers $headers -ContentType 'application/json' -Body $body -TimeoutSec 20
    }
    $body = $null
  }
} catch {
  Remove-Item -LiteralPath $generatedEnvPath -Force -ErrorAction SilentlyContinue
  Stop-WithMessage 'Could not seed the local Admin and Tester accounts. The generated app environment was removed; check the local Auth service and retry.'
} finally {
  $serviceRoleKey = $null
  $headers = $null
  $userList = $null
  $body = $null
  $status = $null
  $statusLines = $null
}

Write-Host 'Local Supabase is ready. The app .env.development.local points only to 127.0.0.1.'
Write-Host 'Run pnpm dev and use the local-only Login as buttons. No production credentials or data are used.'
