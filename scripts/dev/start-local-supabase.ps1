function Stop-WithMessage([string]$Message) {
  throw $Message
}

function Read-DotEnvValue([string]$Line) {
  $separator = $Line.IndexOf('=')
  if ($separator -lt 1) { return $null }
  $value = $Line.Substring($separator + 1).Trim()
  if ($value.StartsWith('"')) {
    try { return ($value | ConvertFrom-Json -ErrorAction Stop) } catch { return $null }
  }
  return $value
}

function Invoke-SupabaseCli([string[]]$Arguments) {
  $previousErrorActionPreference = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try {
    $output = @(& $supabaseCli @Arguments 2>&1)
    $exitCode = $LASTEXITCODE
    return [pscustomobject]@{ ExitCode = $exitCode; Output = $output }
  } finally {
    $ErrorActionPreference = $previousErrorActionPreference
  }
}

function Invoke-LocalSqlFile([string]$SqlPath, [string]$DatabaseContainer) {
  $processInfo = New-Object System.Diagnostics.ProcessStartInfo
  $processInfo.FileName = $dockerCli.Source
  $processInfo.Arguments = "exec -i $DatabaseContainer psql -q -v ON_ERROR_STOP=1 -U postgres -d postgres"
  $processInfo.UseShellExecute = $false
  $processInfo.CreateNoWindow = $true
  $processInfo.RedirectStandardInput = $true
  $processInfo.RedirectStandardOutput = $true
  $processInfo.RedirectStandardError = $true

  $process = New-Object System.Diagnostics.Process
  $process.StartInfo = $processInfo
  $null = $process.Start()
  $stdoutTask = $process.StandardOutput.ReadToEndAsync()
  $stderrTask = $process.StandardError.ReadToEndAsync()
  $sqlText = [System.IO.File]::ReadAllText($SqlPath, [System.Text.Encoding]::UTF8)
  $sqlBytes = [System.Text.Encoding]::UTF8.GetBytes($sqlText)
  $process.StandardInput.BaseStream.Write($sqlBytes, 0, $sqlBytes.Length)
  $process.StandardInput.Close()
  $process.WaitForExit()
  $stdout = $stdoutTask.Result
  $stderr = $stderrTask.Result
  $exitCode = $process.ExitCode
  $process.Dispose()
  [Array]::Clear($sqlBytes, 0, $sqlBytes.Length)
  $sqlBytes = $null
  $sqlText = $null
  return [pscustomobject]@{ ExitCode = $exitCode; Output = $stdout; Error = $stderr }
}

