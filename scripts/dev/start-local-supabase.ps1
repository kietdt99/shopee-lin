if (Test-Path -LiteralPath $legacyImportSqlPath) {
  $generatedSql = [System.IO.File]::ReadAllText($legacyImportSqlPath, [System.Text.Encoding]::UTF8)
  if ($generatedSql -notmatch '(?is)^\s*begin\s*;' -or $generatedSql -notmatch '(?is)commit\s*;\s*(?:--[^\r\n]*)?\s*$') {
    Stop-WithMessage 'The generated legacy SQL does not have a complete BEGIN/COMMIT transaction; it was not applied.'
  }
  $generatedSql = [regex]::Replace($generatedSql, '(?is)^\s*begin\s*;', "BEGIN;`nALTER TABLE public.orders DISABLE TRIGGER protect_closed_cycle_orders;", 1)
  $generatedSql = [regex]::Replace($generatedSql, '(?is)commit\s*;\s*(?:--[^\r\n]*)?\s*$', "ALTER TABLE public.orders ENABLE TRIGGER protect_closed_cycle_orders;`nCOMMIT;", 1)
  [System.IO.File]::WriteAllText($legacyImportApplySqlPath, $generatedSql, (New-Object System.Text.UTF8Encoding($false)))
  $generatedSql = $null
}

